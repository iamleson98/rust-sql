//! SQLite's exact double→text machinery, ported line-for-line from the
//! 3.53.4 amalgamation (`sqlite3FpDecode` / `sqlite3Fp2Convert10` /
//! `sqlite3Fp10Convert2` / the `%!.17g` etGENERIC assembly in
//! `sqlite3_str_vappendf`).
//!
//! Why: SQLite 3.48 replaced the old `%!.15g` REAL→TEXT conversion with a
//! high-precision binary↔decimal pipeline whose 17-digit default
//! (`db->nFpDigit`) additionally SHRINKS the digit count whenever a
//! shorter rendering round-trips back to the same double (the
//! `iRound==17` reduction in `sqlite3FpDecode` — `1e300` renders as
//! `1.0e+300`, not `1.0000000000000001e+300`; `49.47` renders as
//! `49.47`, not `49.469999999999999`). The reference C (including the
//! `aBase` / `aScale` / `aScaleLo` constant tables generated by SQLite's
//! own `tool/mkfptab.c --round`) is copied verbatim; the test suite
//! pins the port byte-for-byte against the real 3.53.4 library across a
//! randomized-double grid (tests/float_text_parity.rs).

// ---------------------------------------------------------------------------
